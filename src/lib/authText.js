const lang = (navigator.language || "it").slice(0, 2);
export const authText = TEXT[lang] || TEXT.it;

/** Turns a Supabase Auth error into a friendly message. */
export function authError(err) {
  const code = err?.code || "";
  const msg = (err?.message || "").toLowerCase();
  if (code === "invalid_credentials" || msg.includes("invalid login")) return authText.err_credentials;
  if (code === "email_not_confirmed" || msg.includes("not confirmed")) return authText.err_not_confirmed;
  if (code === "user_already_exists" || msg.includes("already registered")) return authText.err_exists;
  if (code === "weak_password" || msg.includes("password should")) return authText.err_weak;
  if (code.includes("rate_limit") || err?.status === 429) return authText.err_rate;
  return authText.err_generic;
}
